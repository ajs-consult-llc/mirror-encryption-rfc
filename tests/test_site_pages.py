"""Tests for tools/site_pages.py: the Updates page and the landing block."""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "tools"))

import rfcsync  # noqa: E402
import site_pages  # noqa: E402

SETTINGS = {"repo": "owner/repo", "signup_url": None, "owner": "AJS Consult LLC", "round": 1,
            "opens": "11 November 2026", "closes": "11 December 2026, 23:59 UTC",
            "decisions_by": "25 December 2026", "comment_url": None, "security_contact": "sec@example.com"}
POSTS = [
    {"tag_name": "round-1-open", "name": "Round 1 is open", "published_at": "2026-11-11T18:00:00Z",
     "html_url": "https://github.com/owner/repo/releases/tag/round-1-open",
     "body": "## Where\n\nComment in the review copy.\n```\n# not a heading\n```", "draft": False},
    {"tag_name": "later", "name": "Midpoint", "published_at": "2026-11-26T18:00:00Z",
     "html_url": "https://github.com/owner/repo/releases/tag/later", "body": "Half way.", "draft": False},
    {"tag_name": "secret", "name": "Not yet", "published_at": None, "html_url": "x", "body": "", "draft": True},
]


class Render(unittest.TestCase):
    def setUp(self) -> None:
        self.page = site_pages.updates(SETTINGS, POSTS)

    def test_newest_first_and_drafts_left_out(self) -> None:
        self.assertLess(self.page.index("### Midpoint"), self.page.index("### Round 1 is open"))
        self.assertNotIn("Not yet", self.page)

    def test_post_headings_nest_below_the_post_title_but_code_is_untouched(self) -> None:
        self.assertIn("#### Where", self.page)
        self.assertIn("# not a heading", self.page)
        self.assertNotIn("### not a heading", self.page)

    def test_without_a_signup_link_the_page_says_so(self) -> None:
        self.assertIn("Email sign-up opens shortly.", self.page)
        with_link = site_pages.updates({**SETTINGS, "signup_url": "https://tally.so/r/abc"}, [])
        self.assertIn("[Sign up](https://tally.so/r/abc)", with_link)
        self.assertIn("No updates yet.", with_link)

    def test_confirmation_is_claimed_only_when_the_form_verifies(self) -> None:
        self.assertNotIn("confirmed", self.page)
        verified = site_pages.updates({**SETTINGS, "signup_verifies_email": True}, [])
        self.assertIn("confirmed before they are added", verified)

    def test_the_feed_is_linked(self) -> None:
        self.assertIn("https://github.com/owner/repo/releases.atom", self.page)


class Landing(unittest.TestCase):
    INDEX = "<!-- generated by tools/rfcsync.py: the doc's opening, before its first section -->\n\nOpening line.\n"

    def test_the_block_says_when_and_how(self) -> None:
        block = site_pages.landing(SETTINGS, "chapters/20-appendix-a-submission-process.html")
        self.assertIn("Round 1 is open until 11 December 2026, 23:59 UTC", block)
        self.assertIn("sec@example.com", block)
        self.assertIn("[How submissions work](chapters/20-appendix-a-submission-process.html)", block)
        self.assertIn("posted on the [Updates](updates.html) page", block)  # no review link yet
        linked = site_pages.landing({**SETTINGS, "comment_url": "https://docs.google.com/x"}, None)
        self.assertIn("[In the review copy](https://docs.google.com/x)", linked)

    def test_placing_it_twice_leaves_one_and_stripping_restores_the_index(self) -> None:
        block = site_pages.landing(SETTINGS, None)
        once = site_pages.with_landing(self.INDEX, block)
        twice = site_pages.with_landing(once, block)
        self.assertEqual(once, twice)
        self.assertEqual(once.count(site_pages.LANDING_START), 1)
        self.assertEqual(site_pages.strip_landing(once), self.INDEX)

    def test_the_round_trip_ignores_the_landing_block(self) -> None:
        base = rfcsync.SYNC / "base.md"
        if not base.exists():
            self.skipTest("no export recorded yet")
        original = rfcsync.INDEX.read_text(encoding="utf-8")
        try:
            rfcsync.INDEX.write_text(site_pages.with_landing(original, site_pages.landing(SETTINGS, None)), encoding="utf-8")
            self.assertEqual(rfcsync.join(), base.read_text(encoding="utf-8"))
        finally:
            rfcsync.INDEX.write_text(original, encoding="utf-8")


if __name__ == "__main__":
    unittest.main()
