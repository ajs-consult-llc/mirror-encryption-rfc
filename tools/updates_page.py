#!/usr/bin/env python3
"""Write updates.qmd: how to follow the review, then every update, newest first.

Posts are the repository's GitHub releases, the one source for them. This page, the
repository's feed (``/releases.atom``) and the subscriber email (tools/announce.py) are all
made from the releases, so none of them can disagree with another. The publish workflow runs
this before rendering, and again whenever a release is published, edited or deleted.

    python3 tools/updates_page.py            # writes updates.qmd (generated, not committed)

Settings that are public by nature (the repository, the sign-up link) are in tools/updates.json.
Standard library only; set GITHUB_TOKEN to avoid the anonymous rate limit.
"""
from __future__ import annotations

import json
import os
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SETTINGS = ROOT / "tools" / "updates.json"
OUT = ROOT / "updates.qmd"
FENCE = re.compile(r"^(```|~~~)")


def releases(repo: str) -> list[dict]:
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "mirror-encryption-rfc"}
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(f"https://api.github.com/repos/{repo}/releases?per_page=100", headers=headers)
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.loads(resp.read())


def nest(body: str) -> str:
    """Push a post's own headings below the page's (## for the post title), outside code fences."""
    out, in_fence = [], False
    for line in body.replace("\r\n", "\n").split("\n"):
        if FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence and re.match(r"^#{1,4} ", line):
            line = "##" + line
        out.append(line)
    return "\n".join(out).strip()


def render(settings: dict, posts: list[dict]) -> str:
    repo, signup = settings["repo"], settings.get("signup_url")
    email = (f"[Sign up]({signup}) for review-window notices: when a round opens, its midpoint, "
             "when it closes, and when decisions are published."
             if signup else "Email sign-up opens shortly.")
    lines = [
        "---", 'title: "Updates"', "---", "",
        "<!-- generated by tools/updates_page.py from the repository's releases; edit a release, not this file -->",
        "", "## Follow the review", "",
        f"- **By email.** {email}",
        f"- **By feed.** [releases.atom](https://github.com/{repo}/releases.atom), in any feed reader.",
        f"- **On GitHub.** [Watch the repository](https://github.com/{repo}), then choose Custom and Releases.",
        "",
        ("Email addresses are confirmed before they are added, used only for these notices, never shared, "
         if settings.get("signup_verifies_email") else
         "Email addresses are used only for these notices, never shared, ")
        + "and deleted when the review ends. Every email carries an unsubscribe link.",
        "", "## All updates", "",
    ]
    published = [p for p in posts if not p.get("draft")]
    published.sort(key=lambda p: p.get("published_at") or "", reverse=True)
    if not published:
        lines.append("No updates yet.")
    for p in published:
        date = (p.get("published_at") or "")[:10]
        lines += [f"### {p.get('name') or p['tag_name']}", "",
                  f"*{date}* · [{p['tag_name']}]({p['html_url']})", "", nest(p.get("body") or ""), ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    settings = json.loads(SETTINGS.read_text(encoding="utf-8"))
    OUT.write_text(render(settings, releases(settings["repo"])), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
