#!/usr/bin/env python3
"""Round trip between the Claude Doc and this repository's Quarto book.

    Claude Doc --export--> split --> chapters/*.qmd --> GitHub (PR, review, merge)
    GitHub main --> join --> plan (three-way) --> applied to the Claude Doc

The Claude Doc is where the editor writes. GitHub is the system of record.
They are kept in step by this tool, never by hand:

* ``split`` turns a Markdown export of the doc into one chapter file per
  ``##`` section and regenerates ``_quarto.yml`` from the files it wrote.
  The chapter list is derived from the export, so a section added in the
  doc becomes a chapter without anyone editing the book config.
* ``join`` is the exact inverse of ``split``. ``check`` asserts that
  ``join(split(x)) == x`` byte for byte, so the repository can always be
  turned back into the text the doc holds.
* ``plan`` compares three versions block by block: ``base`` (the last
  export, kept in ``.sync/base.md``), ``ours`` (a fresh export of the
  doc) and ``theirs`` (``join`` of the repository). Every change made on
  GitHub since the last export becomes an instruction to apply in the doc,
  and a block changed on both sides is reported as a conflict instead of
  being overwritten.

Diagrams are widgets in the doc. The export drops them and leaves a
placeholder carrying the diagram's caption; ``split`` swaps each
placeholder for an image link to ``../figures/<slug>.png`` (relative to the chapter) and ``join``
swaps it back, so the placeholder text is what round-trips.

Standard library only. Python 3.9 or later.
"""
from __future__ import annotations

import argparse
import dataclasses
import difflib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHAPTERS = ROOT / "chapters"
FIGURES = ROOT / "figures"
SYNC = ROOT / ".sync"
TEMPLATE = ROOT / "tools" / "_quarto.template.yml"
QUARTO = ROOT / "_quarto.yml"
INDEX = ROOT / "index.qmd"

PLACEHOLDER = re.compile(r"^&#91;embedded content: (?P<caption>.+)\\\]$")
FIGURE = re.compile(r"^!\[(?P<caption>.+)\]\(\.\./figures/(?P<slug>[a-z0-9-]+)\.png\)$")
FENCE = re.compile(r"^(```|~~~)")
INDEX_MARK = "<!-- generated by tools/rfcsync.py: the doc's opening, before its first section -->"


def slugify(text: str) -> str:
    """A filename-safe slug: lowercase ASCII letters, digits and single hyphens."""
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug or "section"


def shift_headings(text: str, delta: int) -> str:
    """Move every ATX heading outside code fences by ``delta`` levels.

    ``split`` promotes (``delta=-1``: ``##`` becomes ``#``) because a Quarto
    chapter starts at level one; ``join`` demotes by the same amount.
    """
    out: list[str] = []
    in_fence = False
    for line in text.split("\n"):
        if FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence:
            m = re.match(r"^(#{1,6}) ", line)
            if m:
                level = len(m.group(1)) + delta
                if not 1 <= level <= 6:
                    raise ValueError(f"heading would leave levels 1-6: {line!r}")
                line = "#" * level + line[len(m.group(1)):]
        out.append(line)
    return "\n".join(out)


def to_figures(text: str) -> str:
    """Replace each diagram placeholder line with an image link."""
    def swap(line: str) -> str:
        m = PLACEHOLDER.match(line)
        if not m:
            return line
        caption = m.group("caption")
        return f"![{caption}](../figures/{slugify(caption)}.png)"  # relative to chapters/
    return "\n".join(swap(line) for line in text.split("\n"))


def to_placeholders(text: str) -> str:
    """The inverse of :func:`to_figures`."""
    def swap(line: str) -> str:
        m = FIGURE.match(line)
        if not m:
            return line
        if m.group("slug") != slugify(m.group("caption")):
            raise ValueError(f"figure file does not match its caption: {line!r}")
        return f"&#91;embedded content: {m.group('caption')}\\]"
    return "\n".join(swap(line) for line in text.split("\n"))


@dataclasses.dataclass(frozen=True)
class Section:
    """One ``##`` section of the export, in document order."""
    heading: str
    body: str  # the section's full text, starting with its own ``##`` line

    @property
    def is_appendix(self) -> bool:
        return self.heading.lower().startswith("appendix")


@dataclasses.dataclass(frozen=True)
class Parsed:
    title: str
    opening: str  # between the title line and the first section
    sections: tuple[Section, ...]


def parse(export: str) -> Parsed:
    lines = export.split("\n")
    if not lines or not lines[0].startswith("# "):
        raise ValueError("the export must start with the doc's '# ' title line")
    title = lines[0][2:]
    starts: list[int] = []
    in_fence = False
    for i, line in enumerate(lines):
        if FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence and line.startswith("## "):
            starts.append(i)
    if not starts:
        raise ValueError("the export has no '## ' sections")
    opening = "\n".join(lines[1:starts[0]])
    sections = []
    for n, start in enumerate(starts):
        end = starts[n + 1] if n + 1 < len(starts) else len(lines)
        sections.append(Section(heading=lines[start][3:], body="\n".join(lines[start:end])))
    return Parsed(title=title, opening=opening, sections=tuple(sections))


def chapter_name(index: int, section: Section) -> str:
    return f"{index:02d}-{slugify(section.heading)}.qmd"


def split(export_path: Path) -> list[Path]:
    """Write ``index.qmd``, one chapter per section, and ``_quarto.yml``."""
    export = export_path.read_text(encoding="utf-8")
    parsed = parse(export)
    CHAPTERS.mkdir(exist_ok=True)
    for old in CHAPTERS.glob("*.qmd"):
        old.unlink()  # a section removed in the doc must not linger as a chapter

    INDEX.write_text(f"{INDEX_MARK}\n{parsed.opening}", encoding="utf-8")
    written: list[Path] = []
    for n, section in enumerate(parsed.sections, start=1):
        path = CHAPTERS / chapter_name(n, section)
        path.write_text(to_figures(shift_headings(section.body, -1)), encoding="utf-8")
        written.append(path)

    chapters = [p for p, s in zip(written, parsed.sections) if not s.is_appendix]
    appendices = [p for p, s in zip(written, parsed.sections) if s.is_appendix]
    items = lambda paths: "\n".join(f"    - {p.relative_to(ROOT)}" for p in paths)  # noqa: E731
    QUARTO.write_text(
        TEMPLATE.read_text(encoding="utf-8")
        .replace("{title}", parsed.title.replace('"', '\\"'))
        .replace("{chapters}", items(chapters))
        .replace("{appendices}", f"  appendices:\n{items(appendices)}" if appendices else ""),
        encoding="utf-8",
    )
    missing = sorted(
        {f"figures/{slugify(m.group('caption'))}.png"
         for line in export.split("\n") if (m := PLACEHOLDER.match(line))}
        - {str(p.relative_to(ROOT)) for p in FIGURES.glob("*.png")}
    )
    for path in missing:
        print(f"warning: no image yet for {path}", file=sys.stderr)
    return written


def book_title() -> str:
    m = re.search(r'^  title: "(?P<t>.*)"$', QUARTO.read_text(encoding="utf-8"), re.M)
    if not m:
        raise ValueError("_quarto.yml has no book title; run split first")
    return m.group("t").replace('\\"', '"')


def join() -> str:
    """Rebuild the export's exact text from ``index.qmd`` and the chapters."""
    opening = INDEX.read_text(encoding="utf-8")
    if not opening.startswith(INDEX_MARK + "\n"):
        raise ValueError("index.qmd lost its generated first line")
    opening = opening[len(INDEX_MARK) + 1:]
    files = sorted(CHAPTERS.glob("*.qmd"))
    bodies = [shift_headings(to_placeholders(p.read_text(encoding="utf-8")), +1) for p in files]
    return "\n".join([f"# {book_title()}", opening, *bodies])


def blocks(text: str) -> list[str]:
    """Blank-line separated blocks: a paragraph, a whole list, a whole table."""
    return [b for b in re.split(r"\n\s*\n", text.strip("\n")) if b.strip()]


def changed_base_indices(base: list[str], other: list[str]) -> set[int]:
    touched: set[int] = set()
    for tag, i1, i2, _j1, _j2 in difflib.SequenceMatcher(None, base, other, autojunk=False).get_opcodes():
        if tag != "equal":
            touched.update(range(max(i1 - 1, 0), max(i2, i1 + 1)))
    return touched


def plan(base_text: str, ours_text: str, theirs_text: str) -> list[dict[str, object]]:
    """Changes made on GitHub (base -> theirs), each marked as a conflict when
    the doc (base -> ours) changed the same blocks or the one just before."""
    base, ours, theirs = blocks(base_text), blocks(ours_text), blocks(theirs_text)
    ours_touched = changed_base_indices(base, ours)
    steps: list[dict[str, object]] = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, base, theirs, autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        span = set(range(max(i1 - 1, 0), max(i2, i1 + 1)))
        steps.append({
            "op": {"replace": "replace", "delete": "delete", "insert": "insert"}[tag],
            "after": base[i1 - 1] if i1 > 0 else None,
            "old": base[i1:i2],
            "new": theirs[j1:j2],
            "conflict": bool(span & ours_touched),
        })
    return steps


def render_plan(steps: list[dict[str, object]]) -> str:
    if not steps:
        return "# Import plan\n\nNothing changed on GitHub since the last export.\n"
    out = ["# Import plan", "",
           f"{len(steps)} change(s) from GitHub; "
           f"{sum(1 for s in steps if s['conflict'])} conflict(s) need the editor.", ""]
    for n, s in enumerate(steps, start=1):
        flag = " — CONFLICT: the doc changed here too" if s["conflict"] else ""
        out += [f"## {n}. {s['op']}{flag}", ""]
        if s["after"]:
            out += ["After the block:", "", "> " + str(s["after"]).replace("\n", "\n> "), ""]
        for label, key in (("Old", "old"), ("New", "new")):
            for block in s[key]:  # type: ignore[union-attr]
                out += [f"{label}:", "", "```markdown", str(block), "```", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("split", help="export Markdown -> chapters and _quarto.yml; records it as the merge base")
    s.add_argument("export", type=Path)
    sub.add_parser("join", help="print the chapters joined back into export form")
    sub.add_parser("check", help="assert join(split(base)) is byte-identical to .sync/base.md")
    p = sub.add_parser("plan", help="three-way plan of GitHub changes to apply to the doc")
    p.add_argument("ours", type=Path, help="a fresh Markdown export of the doc")
    d = sub.add_parser("decode", help="turn a saved Claude Docs export result (JSON, base64) into Markdown")
    d.add_argument("result", type=Path, help="the file the export tool's oversized result was saved to")
    d.add_argument("out", type=Path)
    f = sub.add_parser("figure", help="file a diagram screenshot under its caption's slug")
    f.add_argument("caption", help="the embed's caption, exactly as the doc shows it")
    f.add_argument("png", type=Path)
    args = ap.parse_args(argv)

    if args.cmd == "decode":
        import base64
        data = json.loads(args.result.read_text(encoding="utf-8"))["data"]
        if data.get("format") != "markdown":
            print(f"error: expected a markdown export, got {data.get('format')!r}", file=sys.stderr)
            return 1
        args.out.write_bytes(base64.b64decode(data["bytes_b64"]))
        for note in data.get("notes", []):
            print(f"note: {note.get('code')}: {note.get('count')} {note.get('what')}")
        print(f"wrote {args.out} ({data.get('bytes')} bytes)")
        return 0
    if args.cmd == "figure":
        FIGURES.mkdir(exist_ok=True)
        target = FIGURES / f"{slugify(args.caption)}.png"
        target.write_bytes(args.png.read_bytes())
        print(target.relative_to(ROOT))
        return 0
    if args.cmd == "split":
        written = split(args.export)
        SYNC.mkdir(exist_ok=True)
        (SYNC / "base.md").write_text(args.export.read_text(encoding="utf-8"), encoding="utf-8")
        if join() != args.export.read_text(encoding="utf-8"):
            print("error: the split does not round-trip; nothing should be committed", file=sys.stderr)
            return 1
        print(f"wrote index.qmd, {len(written)} chapters, _quarto.yml; base recorded; round trip exact")
        return 0
    if args.cmd == "join":
        sys.stdout.write(join())
        return 0
    if args.cmd == "check":
        base = (SYNC / "base.md").read_text(encoding="utf-8")
        joined = join()
        if joined == base:
            print("round trip exact")
            return 0
        diff = difflib.unified_diff(base.split("\n"), joined.split("\n"), "base.md", "joined", lineterm="")
        print("\n".join(list(diff)[:80]))
        print("the chapters differ from the last export: run plan before the next split", file=sys.stderr)
        return 1
    if args.cmd == "plan":
        steps = plan((SYNC / "base.md").read_text(encoding="utf-8"),
                     args.ours.read_text(encoding="utf-8"), join())
        (SYNC / "import-plan.json").write_text(json.dumps(steps, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        (SYNC / "import-plan.md").write_text(render_plan(steps), encoding="utf-8")
        conflicts = sum(1 for s in steps if s["conflict"])
        print(f"{len(steps)} change(s), {conflicts} conflict(s): see .sync/import-plan.md")
        return 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
