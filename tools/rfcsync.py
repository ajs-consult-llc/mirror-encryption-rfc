#!/usr/bin/env python3
"""Round trip between the Claude Doc and this repository's Markdown.

    Claude Doc --export--> split --> index.md + chapters/*.md --> GitHub (PR, review, merge)
    GitHub main --> join --> plan (three-way) --> applied to the Claude Doc

The Claude Doc is where the editor writes. GitHub is the system of record, and everything in
it is plain Markdown that GitHub shows as a page: text, tables, and diagrams as Mermaid.
The two are kept in step by this tool, never by hand:

* ``split`` turns a Markdown export of the doc into ``index.md`` (the doc's opening) and one
  chapter file per ``##`` section, and regenerates ``_quarto.yml`` from the files it wrote,
  so a section added in the doc becomes a chapter without anyone editing the book config.
* Diagrams are widgets in the doc. The export drops them and leaves a placeholder carrying
  the diagram's caption. ``split`` puts the picture exported from the doc
  (``figures/<slug>.png``) in its place, with a link to its text version, and writes a last
  appendix, "The diagrams as text", from ``diagrams/<slug>.mmd``: each diagram's description
  and Mermaid source. ``join`` turns each picture back into the placeholder and skips the
  generated appendix. A caption used twice gets ``-2``, ``-3`` on its later slugs.
* ``stale`` lists the diagrams whose picture changed in the doc (its widget's publish number,
  recorded in ``.sync/widgets.json``) since their Mermaid was last checked against it.
* ``join`` is the exact inverse of ``split``; ``check`` asserts ``join(split(x)) == x`` byte
  for byte. ``join`` refuses a diagram block edited inside a chapter: pictures change in
  ``figures/`` and text versions in ``diagrams/``, then ``split`` rewrites the chapters.
* ``plan`` compares three versions block by block: ``base`` (the last export, kept in
  ``.sync/base.md``), ``ours`` (a fresh export of the doc) and ``theirs`` (``join`` of the
  repository). Every change merged on GitHub since the last export becomes an instruction to
  apply in the doc; a block changed on both sides is reported as a conflict.

Standard library only. Python 3.9 or later.
"""
from __future__ import annotations

import argparse
import dataclasses
import difflib
import json
import re
import sys
from pathlib import Path

from site_pages import strip_landing  # the landing block is the site's, never the doc's

ROOT = Path(__file__).resolve().parent.parent
CHAPTERS = ROOT / "chapters"
DIAGRAMS = ROOT / "diagrams"
FIGURES = ROOT / "figures"
SYNC = ROOT / ".sync"
TEMPLATE = ROOT / "tools" / "_quarto.template.yml"
QUARTO = ROOT / "_quarto.yml"
INDEX = ROOT / "index.md"

PLACEHOLDER = re.compile(r"^&#91;embedded content: (?P<caption>.+)\\\]$")
DIAGRAM_MARK = re.compile(r"^<!-- diagram: (?P<caption>.+) -->$")
DIAGRAM_END = "<!-- /diagram -->"
APPENDIX_MARK = "<!-- generated by tools/rfcsync.py from diagrams/*.mmd: not in the doc, and join skips it -->"
APPENDIX_INTRO = (
    "Every diagram in this document, written out: a description in words, for screen readers and "
    "search, and its source in [Mermaid](https://mermaid.js.org), which GitHub draws and anyone can "
    "edit in a pull request. The pictures in the chapters are exported from the editor's document; "
    "these text versions are kept in step with them, and the sync tool reports any picture that has "
    "changed since its text version was last checked."
)
MERMAID_OPEN = re.compile(r"^```(mermaid|\{mermaid\})$")
FENCE = re.compile(r"^(```|~~~)")
INDEX_MARK = "<!-- generated by tools/rfcsync.py: the doc's opening, before its first section -->"


def slugify(text: str) -> str:
    """A filename-safe slug: lowercase ASCII letters, digits and single hyphens."""
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug or "section"


class DiagramNames:
    """Hands out a unique slug per caption, in document order: the second use of a caption
    gets ``-2``. One instance spans a whole split or join, so the numbering is the document's."""

    def __init__(self) -> None:
        self.seen: dict[str, int] = {}

    def next(self, caption: str) -> str:
        base = slugify(caption)
        self.seen[base] = self.seen.get(base, 0) + 1
        n = self.seen[base]
        return base if n == 1 else f"{base}-{n}"


def shift_headings(text: str, delta: int) -> str:
    """Move every ATX heading outside code fences by ``delta`` levels.

    ``split`` promotes (``delta=-1``: ``##`` becomes ``#``) because a chapter starts at level
    one; ``join`` demotes by the same amount.
    """
    out: list[str] = []
    in_fence = False
    for line in text.split("\n"):
        if FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence:
            m = re.match(r"^(#{1,6}) ", line)
            if m:
                level = len(m.group(1)) + delta
                if not 1 <= level <= 6:
                    raise ValueError(f"heading would leave levels 1-6: {line!r}")
                line = "#" * level + line[len(m.group(1)):]
        out.append(line)
    return "\n".join(out)


@dataclasses.dataclass(frozen=True)
class TextVersion:
    """A diagram's Mermaid file, read: its title and description come from accTitle and accDescr."""
    title: str
    description: str
    source: str


def text_version(slug: str) -> TextVersion | None:
    """``diagrams/<slug>.mmd`` read, or None when the diagram has no text version yet."""
    src = DIAGRAMS / f"{slug}.mmd"
    if not src.exists():
        return None
    source = src.read_text(encoding="utf-8").rstrip("\n")
    title = re.search(r"^\s*accTitle: (.+)$", source, re.M)
    desc = re.search(r"^\s*accDescr: (.+)$", source, re.M)
    return TextVersion(title.group(1) if title else "", desc.group(1) if desc else "", source)


@dataclasses.dataclass(frozen=True)
class Diagram:
    """One diagram placeholder of the export, where it fell."""
    caption: str
    slug: str
    chapter: str  # the file it is shown in, relative to chapters/
    heading: str  # that chapter's heading


def figure_lines(caption: str, slug: str, figures_href: str, appendix_href: str | None) -> list[str] | None:
    """What stands in a chapter for one diagram: the picture exported from the doc, and a link to
    its text version. None when the picture has not been exported yet."""
    if not (FIGURES / f"{slug}.png").exists():
        return None
    text = text_version(slug)
    alt = text.title if text and text.title else caption
    lines = [f"<!-- diagram: {caption} -->", f"![{alt}]({figures_href}{slug}.png)"]
    if text and appendix_href:
        lines += ["", f"*[This diagram as text]({appendix_href}#{slug})*"]
    return lines + [DIAGRAM_END]


def to_diagrams(text: str, names: DiagramNames, missing: list[str], *, figures_href: str = "../figures/",
                appendix_href: str | None = None, chapter: str = "", heading: str = "",
                found: list[Diagram] | None = None) -> str:
    """Replace each diagram placeholder with its exported picture and a link to its text version.
    A placeholder whose picture is not in figures/ yet is left as it is, and reported."""
    out: list[str] = []
    for line in text.split("\n"):
        m = PLACEHOLDER.match(line)
        if not m:
            out.append(line)
            continue
        caption = m.group("caption")
        slug = names.next(caption)
        block = figure_lines(caption, slug, figures_href, appendix_href)
        if block is None:
            missing.append(f"figures/{slug}.png")
            out.append(line)
            continue
        if text_version(slug) is None:
            missing.append(f"diagrams/{slug}.mmd")
        if found is not None:
            found.append(Diagram(caption, slug, chapter, heading))
        out += block
    return "\n".join(out)


def to_placeholders(text: str, names: DiagramNames, *, figures_href: str = "../figures/",
                    appendix_href: str | None = None) -> str:
    """The inverse of :func:`to_diagrams`. Refuses a diagram block edited by hand."""
    lines, out, i = text.split("\n"), [], 0
    while i < len(lines):
        m = DIAGRAM_MARK.match(lines[i])
        if m:
            end = i + 1
            while end < len(lines) and lines[end] != DIAGRAM_END:
                end += 1
            if end == len(lines):
                raise ValueError(f"the diagram {m.group('caption')!r} has no closing {DIAGRAM_END}")
            caption = m.group("caption")
            expected = figure_lines(caption, names.next(caption), figures_href, appendix_href)
            if expected != lines[i:end + 1]:
                raise ValueError(f"the diagram block for {caption!r} was edited: change figures/ or "
                                 "diagrams/ and run split, never the block inside a chapter")
            out.append(f"&#91;embedded content: {caption}\\]")
            i = end + 1
            continue
        out.append(lines[i])
        i += 1
    return "\n".join(out)


def appendix_letter(sections: "tuple[Section, ...]") -> str:
    return "ABCDEFGHIJKLMNOPQRSTUVWXYZ"[sum(1 for sec in sections if sec.is_appendix)]


def appendix_text(letter: str, diagrams: list[Diagram]) -> str:
    """The generated appendix: every diagram's description and Mermaid source, in document order."""
    out = [APPENDIX_MARK, f"# Appendix {letter}. The diagrams as text", "", APPENDIX_INTRO, ""]
    for d in diagrams:
        text = text_version(d.slug)
        if text is None:
            continue
        out += [f'<a id="{d.slug}"></a>', "", f"## {text.title or d.caption}", "",
                f"In [{d.heading}]({d.chapter}). {text.description}".rstrip(), "",
                "```mermaid", text.source, "```", ""]
    return "\n".join(out)


def is_generated(path: Path) -> bool:
    with path.open(encoding="utf-8") as f:
        return f.readline().rstrip("\n") == APPENDIX_MARK


@dataclasses.dataclass(frozen=True)
class Section:
    """One ``##`` section of the export, in document order."""
    heading: str
    body: str  # the section's full text, starting with its own ``##`` line

    @property
    def is_appendix(self) -> bool:
        return self.heading.lower().startswith("appendix")


@dataclasses.dataclass(frozen=True)
class Parsed:
    title: str
    opening: str  # between the title line and the first section
    sections: tuple[Section, ...]


def parse(export: str) -> Parsed:
    lines = export.split("\n")
    if not lines or not lines[0].startswith("# "):
        raise ValueError("the export must start with the doc's '# ' title line")
    title = lines[0][2:]
    starts: list[int] = []
    in_fence = False
    for i, line in enumerate(lines):
        if FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence and line.startswith("## "):
            starts.append(i)
    if not starts:
        raise ValueError("the export has no '## ' sections")
    opening = "\n".join(lines[1:starts[0]])
    sections = []
    for n, start in enumerate(starts):
        end = starts[n + 1] if n + 1 < len(starts) else len(lines)
        sections.append(Section(heading=lines[start][3:], body="\n".join(lines[start:end])))
    return Parsed(title=title, opening=opening, sections=tuple(sections))


def chapter_name(index: int, section: Section) -> str:
    return f"{index:02d}-{slugify(section.heading)}.md"


def split(export_path: Path) -> list[Path]:
    """Write ``index.md``, one chapter per section, and ``_quarto.yml``."""
    export = export_path.read_text(encoding="utf-8")
    parsed = parse(export)
    CHAPTERS.mkdir(exist_ok=True)
    for old in [*CHAPTERS.glob("*.md"), *CHAPTERS.glob("*.qmd"), ROOT / "index.qmd"]:
        old.unlink(missing_ok=True)  # a section removed in the doc must not linger as a chapter

    letter = appendix_letter(parsed.sections)
    generated = CHAPTERS / f"{len(parsed.sections) + 1:02d}-appendix-{letter.lower()}-the-diagrams-as-text.md"
    names, missing, found = DiagramNames(), [], []
    INDEX.write_text(f"{INDEX_MARK}\n" + to_diagrams(
        parsed.opening, names, missing, figures_href="figures/", appendix_href=f"chapters/{generated.name}",
        chapter=f"../{INDEX.name}", heading="the opening", found=found), encoding="utf-8")
    written: list[Path] = []
    for n, section in enumerate(parsed.sections, start=1):
        path = CHAPTERS / chapter_name(n, section)
        path.write_text(to_diagrams(shift_headings(section.body, -1), names, missing, appendix_href=generated.name,
                                    chapter=path.name, heading=section.heading, found=found), encoding="utf-8")
        written.append(path)
    if any(text_version(d.slug) for d in found):
        generated.write_text(appendix_text(letter, found), encoding="utf-8")

    chapters = [p for p, s in zip(written, parsed.sections) if not s.is_appendix]
    appendices = [p for p, s in zip(written, parsed.sections) if s.is_appendix]
    if generated.exists():
        appendices.append(generated)
    items = lambda paths: "\n".join(f"    - {p.relative_to(ROOT)}" for p in paths)  # noqa: E731
    QUARTO.write_text(
        TEMPLATE.read_text(encoding="utf-8")
        .replace("{title}", parsed.title.replace('"', '\\"'))
        .replace("{chapters}", items(chapters))
        .replace("{appendices}", f"  appendices:\n{items(appendices)}" if appendices else ""),
        encoding="utf-8",
    )
    for path in missing:
        what = "the picture stays a placeholder" if path.startswith("figures/") else "no text version in the appendix"
        print(f"warning: {path} is missing; {what}", file=sys.stderr)
    return written


def book_title() -> str:
    m = re.search(r'^  title: "(?P<t>.*)"$', QUARTO.read_text(encoding="utf-8"), re.M)
    if not m:
        raise ValueError("_quarto.yml has no book title; run split first")
    return m.group("t").replace('\\"', '"')


def join() -> str:
    """Rebuild the export's exact text from ``index.md`` and the chapters."""
    opening = strip_landing(INDEX.read_text(encoding="utf-8"))
    if not opening.startswith(INDEX_MARK + "\n"):
        raise ValueError("index.md lost its generated first line")
    names = DiagramNames()
    files = sorted(CHAPTERS.glob("*.md"))
    generated = [p for p in files if is_generated(p)]
    appendix = generated[0].name if generated else None
    opening = to_placeholders(opening[len(INDEX_MARK) + 1:], names, figures_href="figures/",
                              appendix_href=f"chapters/{appendix}" if appendix else None)
    bodies = [shift_headings(to_placeholders(p.read_text(encoding="utf-8"), names, appendix_href=appendix), +1)
              for p in files if p not in generated]
    return "\n".join([f"# {book_title()}", opening, *bodies])


def blocks(text: str) -> list[str]:
    """Blank-line separated blocks: a paragraph, a whole list, a whole table."""
    return [b for b in re.split(r"\n\s*\n", text.strip("\n")) if b.strip()]


def changed_base_indices(base: list[str], other: list[str]) -> set[int]:
    touched: set[int] = set()
    for tag, i1, i2, _j1, _j2 in difflib.SequenceMatcher(None, base, other, autojunk=False).get_opcodes():
        if tag != "equal":
            touched.update(range(max(i1 - 1, 0), max(i2, i1 + 1)))
    return touched


def plan(base_text: str, ours_text: str, theirs_text: str) -> list[dict[str, object]]:
    """Changes made on GitHub (base -> theirs), each marked as a conflict when
    the doc (base -> ours) changed the same blocks or the one just before."""
    base, ours, theirs = blocks(base_text), blocks(ours_text), blocks(theirs_text)
    ours_touched = changed_base_indices(base, ours)
    steps: list[dict[str, object]] = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, base, theirs, autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        span = set(range(max(i1 - 1, 0), max(i2, i1 + 1)))
        steps.append({
            "op": {"replace": "replace", "delete": "delete", "insert": "insert"}[tag],
            "after": base[i1 - 1] if i1 > 0 else None,
            "old": base[i1:i2],
            "new": theirs[j1:j2],
            "conflict": bool(span & ours_touched),
        })
    return steps


def render_plan(steps: list[dict[str, object]]) -> str:
    if not steps:
        return "# Import plan\n\nNothing changed on GitHub since the last export.\n"
    out = ["# Import plan", "",
           f"{len(steps)} change(s) from GitHub; "
           f"{sum(1 for s in steps if s['conflict'])} conflict(s) need the editor.", ""]
    for n, s in enumerate(steps, start=1):
        flag = " — CONFLICT: the doc changed here too" if s["conflict"] else ""
        out += [f"## {n}. {s['op']}{flag}", ""]
        if s["after"]:
            out += ["After the block:", "", "> " + str(s["after"]).replace("\n", "\n> "), ""]
        for label, key in (("Old", "old"), ("New", "new")):
            for block in s[key]:  # type: ignore[union-attr]
                out += [f"{label}:", "", "```markdown", str(block), "```", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("split", help="export Markdown -> index.md, chapters and _quarto.yml; records the merge base")
    s.add_argument("export", type=Path)
    sub.add_parser("join", help="print the chapters joined back into export form")
    sub.add_parser("check", help="assert join(split(base)) is byte-identical to .sync/base.md")
    p = sub.add_parser("plan", help="three-way plan of GitHub changes to apply to the doc")
    p.add_argument("ours", type=Path, help="a fresh Markdown export of the doc")
    sub.add_parser("stale", help="list diagrams whose picture changed in the doc since their Mermaid was checked")
    d = sub.add_parser("decode", help="turn a saved Claude Docs export result (JSON, base64) into Markdown")
    d.add_argument("result", type=Path, help="the file the export tool's oversized result was saved to")
    d.add_argument("out", type=Path)
    args = ap.parse_args(argv)

    if args.cmd == "decode":
        import base64
        data = json.loads(args.result.read_text(encoding="utf-8"))["data"]
        if data.get("format") != "markdown":
            print(f"error: expected a markdown export, got {data.get('format')!r}", file=sys.stderr)
            return 1
        args.out.write_bytes(base64.b64decode(data["bytes_b64"]))
        for note in data.get("notes", []):
            print(f"note: {note.get('code')}: {note.get('count')} {note.get('what')}")
        print(f"wrote {args.out} ({data.get('bytes')} bytes)")
        return 0
    if args.cmd == "split":
        written = split(args.export)
        SYNC.mkdir(exist_ok=True)
        (SYNC / "base.md").write_text(args.export.read_text(encoding="utf-8"), encoding="utf-8")
        if join() != args.export.read_text(encoding="utf-8"):
            print("error: the split does not round-trip; nothing should be committed", file=sys.stderr)
            return 1
        print(f"wrote index.md, {len(written)} chapters, _quarto.yml; base recorded; round trip exact")
        return 0
    if args.cmd == "join":
        sys.stdout.write(join())
        return 0
    if args.cmd == "check":
        base = (SYNC / "base.md").read_text(encoding="utf-8")
        joined = join()
        if joined == base:
            print("round trip exact")
            return 0
        diff = difflib.unified_diff(base.split("\n"), joined.split("\n"), "base.md", "joined", lineterm="")
        print("\n".join(list(diff)[:80]))
        print("the chapters differ from the last export: run plan before the next split", file=sys.stderr)
        return 1
    if args.cmd == "stale":
        widgets = json.loads((SYNC / "widgets.json").read_text(encoding="utf-8"))["diagrams"]
        stale = {slug: w for slug, w in widgets.items() if w.get("pub") != w.get("mermaid_pub")}
        for slug, w in stale.items():
            print(f"stale: diagrams/{slug}.mmd was checked against publish {w.get('mermaid_pub')} of its "
                  f"widget; the picture is publish {w.get('pub')}")
        if not stale:
            print(f"all {len(widgets)} text versions match their pictures")
        return 1 if stale else 0
    if args.cmd == "plan":
        steps = plan((SYNC / "base.md").read_text(encoding="utf-8"),
                     args.ours.read_text(encoding="utf-8"), join())
        (SYNC / "import-plan.json").write_text(json.dumps(steps, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        (SYNC / "import-plan.md").write_text(render_plan(steps), encoding="utf-8")
        conflicts = sum(1 for s in steps if s["conflict"])
        print(f"{len(steps)} change(s), {conflicts} conflict(s): see .sync/import-plan.md")
        return 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
