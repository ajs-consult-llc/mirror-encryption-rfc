#!/usr/bin/env python3
"""Write the pages a visitor needs before the document: the landing block and Updates.

    python3 tools/site_pages.py     # run by the publish workflow before rendering

* **The landing block** goes at the top of ``index.md``, between two markers, so someone
  arriving from a shared link learns what this is, how to take part and by when, before the
  document starts. ``tools/rfcsync.py join`` strips everything between the markers, so the
  round trip with the Claude Doc never sees it.
* **updates.qmd** is how to follow the review, then every update, newest first, made from the
  repository's GitHub releases. The releases are the one source for posts: this page, the
  feed (``/releases.atom``) and the subscriber email (tools/announce.py) are all made from them.

Every fact about the round (dates, links, the security contact) is in tools/review.json, and
both pages read it from there. Standard library only; set GITHUB_TOKEN to avoid the
anonymous rate limit.
"""
from __future__ import annotations

import json
import os
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SETTINGS = ROOT / "tools" / "review.json"
INDEX = ROOT / "index.md"
UPDATES = ROOT / "updates.qmd"
CHAPTERS = ROOT / "chapters"
LANDING_START = "<!-- landing:start (generated by tools/site_pages.py; rfcsync join strips it) -->"
LANDING_END = "<!-- landing:end -->"
FENCE = re.compile(r"^(```|~~~)")


def releases(repo: str) -> list[dict]:
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "mirror-encryption-rfc"}
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(f"https://api.github.com/repos/{repo}/releases?per_page=100", headers=headers)
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.loads(resp.read())


def chapter_link(slug_part: str) -> str | None:
    """The rendered page of the chapter whose file name contains ``slug_part``, if there is one."""
    found = sorted(CHAPTERS.glob(f"*{slug_part}*.md"))
    return f"chapters/{found[0].stem}.html" if found else None


def landing(s: dict, submission_page: str | None) -> str:
    comment = (f"[In the review copy]({s['comment_url']}), signed in to a Google account. "
               "Each comment is credited to the account that wrote it."
               if s.get("comment_url") else
               "In the review copy, signed in to a Google account. Its link is posted on the "
               "[Updates](updates.html) page when the round opens.")
    how = f" [How submissions work]({submission_page})." if submission_page else ""
    return "\n".join([
        LANDING_START,
        "",
        # The white version, marked as the page's link preview: Quarto would otherwise send the first
        # image on the page, and a transparent preview looks broken on dark-mode feeds.
        "![Cloud Data Mirror RFC: your data, encrypted with your key, readable only by the AI you approve]"
        "(assets/social/cloud-data-mirror-social.png){.preview-image}",
        "",
        "::: {.callout-note appearance=\"simple\"}",
        f"**Request for comments. Round {s['round']} is open until {s['closes']}.**",
        ":::",
        "",
        "**What this is.** A security reference architecture for cloud data mirrors: a private "
        "copy of a person's messages and data that only the readers they choose, including their AI "
        f"assistants, can search. {s['owner']} publishes it for open review.",
        "",
        "**How to take part**",
        "",
        "1. **Read it.** Start with the executive summary.",
        f"2. **Comment.** {comment}{how}",
        "3. **Follow the review.** [Updates](updates.html): sign up by email, use the feed, or watch on GitHub.",
        f"4. **Found a security problem in the running service?** Email {s['security_contact']} with "
        "SECURITY in the subject. Never post it in a comment.",
        "",
        "| Round " + str(s["round"]) + " | |",
        "| --- | --- |",
        f"| Opens | {s['opens']} |",
        f"| Comments close | {s['closes']} |",
        f"| Decisions published | By {s['decisions_by']} |",
        "",
        LANDING_END,
    ])


def with_landing(index_text: str, block: str) -> str:
    """index.qmd with the landing block placed after its first line, replacing any earlier one."""
    text = strip_landing(index_text)
    first, sep, rest = text.partition("\n")
    return f"{first}\n{block}\n{rest}" if sep else f"{first}\n{block}\n"


def strip_landing(text: str) -> str:
    start = text.find(LANDING_START)
    if start == -1:
        return text
    end = text.find(LANDING_END, start)
    if end == -1:
        raise ValueError("index.qmd has a landing start marker without its end")
    end += len(LANDING_END)
    if text[end:end + 1] == "\n":
        end += 1
    return text[:start] + text[end:]


def nest(body: str) -> str:
    """Push a post's own headings below the page's (### for the post title), outside code fences."""
    out, in_fence = [], False
    for line in body.replace("\r\n", "\n").split("\n"):
        if FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence and re.match(r"^#{1,4} ", line):
            line = "##" + line
        out.append(line)
    return "\n".join(out).strip()


def updates(s: dict, posts: list[dict]) -> str:
    repo, signup = s["repo"], s.get("signup_url")
    email = (f"[Sign up]({signup}) for review-window notices: when a round opens, its midpoint, "
             "when it closes, and when decisions are published."
             if signup else "Email sign-up opens shortly.")
    lines = [
        "---", 'title: "Updates"', "---", "",
        "<!-- generated by tools/site_pages.py from the repository's releases; edit a release, not this file -->",
        "", "## Follow the review", "",
        f"- **By email.** {email}",
        f"- **By feed.** [releases.atom](https://github.com/{repo}/releases.atom), in any feed reader.",
        f"- **On GitHub.** [Watch the repository](https://github.com/{repo}), then choose Custom and Releases.",
        "",
        ("Email addresses are confirmed before they are added, used only for these notices, never shared, "
         if s.get("signup_verifies_email") else
         "Email addresses are used only for these notices, never shared, ")
        + "and deleted when the review ends. Every email carries an unsubscribe link.",
        "", "## All updates", "",
    ]
    published = [p for p in posts if not p.get("draft")]
    published.sort(key=lambda p: p.get("published_at") or "", reverse=True)
    if not published:
        lines.append("No updates yet.")
    for p in published:
        date = (p.get("published_at") or "")[:10]
        lines += [f"### {p.get('name') or p['tag_name']}", "",
                  f"*{date}* · [{p['tag_name']}]({p['html_url']})", "", nest(p.get("body") or ""), ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    s = json.loads(SETTINGS.read_text(encoding="utf-8"))
    UPDATES.write_text(updates(s, releases(s["repo"])), encoding="utf-8")
    INDEX.write_text(with_landing(INDEX.read_text(encoding="utf-8"),
                                  landing(s, chapter_link("submission-process"))), encoding="utf-8")
    print("wrote updates.qmd and the landing block in index.qmd")
    return 0


if __name__ == "__main__":
    sys.exit(main())
